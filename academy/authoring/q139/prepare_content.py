def _ordinal(n):  # qbuild.ordinal 只支援 1–99；第 100 堂起用這個（不改共用程式）
    cn = '零一二三四五六七八九'
    if n < 100:
        return _ord99(n)
    h, r = divmod(n, 100)
    if r == 0:
        return cn[h] + '百'
    return cn[h] + '百' + ('零' + cn[r] if r < 10 else ('一' + _ord99(r) if r < 20 else _ord99(r)))


